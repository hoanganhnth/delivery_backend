#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { parseGatewayRouteSource } from './public-edge-manifest-lib.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const backend = path.resolve(here, '../../../..');
const gatewayRelative = 'api-gateway/src/main/java/com/delivery/api_gateway/config/GatewayRouteConfig.java';
const gatewayPath = path.join(backend, gatewayRelative);
const manifestPath = path.join(here, 'public-edge-manifest.json');
const catalogPath = path.join(here, 'public-edge-catalog.md');
const write = process.argv.includes('--write');
const check = process.argv.includes('--check');

if ((write && check) || (!write && !check)) {
  console.error('Usage: node generate-public-edge-manifest.mjs --write|--check');
  process.exit(2);
}

const projection = parseGatewayRouteSource(fs.readFileSync(gatewayPath, 'utf8'), {
  file: gatewayRelative,
});
const manifest = {
  format: 1,
  title: 'Delivery public-edge route manifest',
  generatedFrom: gatewayRelative,
  scope: 'Exact Spring Cloud Gateway route declarations. This projection does not auto-publish controllers and does not replace downstream authentication, role or ownership checks.',
  counts: projection.counts,
  routes: projection.routes,
};
const manifestContent = `${JSON.stringify(manifest, null, 2)}\n`;

function cell(value) {
  return String(value ?? '—')
    .replace(/\\/g, '\\\\')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, '<br>');
}

function code(value) {
  return `\`${cell(value).replace(/`/g, '\\`')}\``;
}

function table(headers, rows) {
  return [
    `| ${headers.map(cell).join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n');
}

function gateLabel(route) {
  if (route.featureGate.mode === 'always') return 'always';
  return `${route.featureGate.property} (default ${route.featureGate.default})`;
}

function sourceLink(source) {
  return `[${code(`${source.file}:${source.line}`)}](../../../../${source.file}#L${source.line})`;
}

const catalogLines = [
  '# Public Edge Route Catalog',
  '',
  '> Generated by `generate-public-edge-manifest.mjs`; do not edit by hand.',
  '> This is a review projection of `GatewayRouteConfig.java`, not an authority',
  '> that makes a controller public and not proof of downstream authorization.',
  '',
  `Current edge: **${manifest.counts.routes} route declarations** and **${manifest.counts.pathPatterns} path patterns**.`,
  '',
  '## Feature-gate summary',
  '',
  table(
    ['Gate', 'Route declarations'],
    Object.entries(manifest.counts.byGate).map(([gate, count]) => [gate, count]),
  ),
  '',
  '## Route declarations',
  '',
  table(
    ['Route ID', 'Methods', 'Path patterns', 'Downstream', 'Feature gate', 'Rewrite', 'Source'],
    manifest.routes.map((route) => [
      code(route.id),
      route.methods.map(code).join(', '),
      route.paths.map(code).join('<br>'),
      `${code(route.downstream.service)}<br>${code(route.downstream.defaultUri)}`,
      code(gateLabel(route)),
      route.rewrite ? `${code(route.rewrite.from)} → ${code(route.rewrite.to)}` : '—',
      sourceLink(route.source),
    ]),
  ),
  '',
  '## Cross-cutting policy boundary',
  '',
  'Rate-limit classification is intentionally recorded as `request-dependent` on',
  'each route. The runtime classifier uses the concrete request method/path and',
  'remains authoritative in',
  '[`GatewayRateLimitFilter.java`](../../../../api-gateway/src/main/java/com/delivery/api_gateway/ratelimit/GatewayRateLimitFilter.java).',
  'The manifest does not duplicate quota or fail-open/fail-closed policy.',
];
const catalogContent = `${catalogLines.join('\n')}\n`;

if (write) {
  fs.writeFileSync(manifestPath, manifestContent);
  fs.writeFileSync(catalogPath, catalogContent);
  console.log(`Wrote public-edge manifest and catalog with ${manifest.counts.routes} routes and ${manifest.counts.pathPatterns} path patterns.`);
} else {
  const manifestMatches = fs.existsSync(manifestPath)
    && fs.readFileSync(manifestPath, 'utf8') === manifestContent;
  const catalogMatches = fs.existsSync(catalogPath)
    && fs.readFileSync(catalogPath, 'utf8') === catalogContent;
  if (!manifestMatches || !catalogMatches) {
    console.error('Public-edge manifest or catalog is stale or missing; run generate-public-edge-manifest.mjs --write');
    process.exitCode = 1;
  } else {
    console.log(`PASS: public-edge manifest has ${manifest.counts.routes} routes and ${manifest.counts.pathPatterns} path patterns.`);
  }
}
